const VALID_DOMAINS=new Set(["business","politics","community","media","relationships","economics","legacy","knowledge","adversarial"]);
const fields=["opening","bottleneck","countermove","callback"];
export function validateCases(items=STRATEGIC_CASEBOOK){
 const errors=[],ids=new Set();
 for(const c of items){
  if(!/^CASE-\d{2}$/.test(c.id)||ids.has(c.id))errors.push("Bad/duplicate case ID "+c.id);
  ids.add(c.id);
  if(!VALID_DOMAINS.has(c.domain))errors.push("Bad domain "+c.id);
  if(!["micro","meso","macro"].includes(c.scale))errors.push("Bad scale "+c.id);
  for(const f of fields)if(typeof c[f]!=="string"||c[f].length<35)errors.push("Weak "+f+" "+c.id);
  if(!Array.isArray(c.actors)||c.actors.length<2||
    c.actors.some(a=>a.length!==3||a.some(x=>!x)))errors.push("Weak cast "+c.id);
  if(!Array.isArray(c.mechanisms)||c.mechanisms.length<3||
    c.mechanisms.some(id=>!/^SM-\d{3}$/.test(id)))errors.push("Bad mechanisms "+c.id);
 }
 return {valid:errors.length===0,count:items.length,errors};
}
/** Safe framing: expose public setup, not private motivations / hidden planned developments. */
export function getPublicCase(id){
 const c=STRATEGIC_CASEBOOK.find(x=>x.id===id);
 if(!c)throw Error("Unknown case");
 return {id:c.id,title:c.title,domain:c.domain,opening:c.opening,
  cast:c.actors.map(([name,role])=>({name,role})),issue:c.bottleneck};
}
