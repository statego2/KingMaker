export function validateMechanisms(items=STRATEGIC_MECHANISMS){
 const errors=[],seen=new Set();
 for(const [i,p] of items.entries()){
  if(!/^SM-\d{3}$/.test(p?.id??""))errors.push("invalid ID "+i);
  if(seen.has(p.id))errors.push("duplicate ID "+p.id);
  seen.add(p.id);
  if(!CANON_DOMAINS.includes(p.domain))errors.push("unknown domain "+p.id);
  if(!MASTER_TENSIONS.includes(p.tension))errors.push("unknown tension "+p.id);
  for(const k of ["name","signal","lever","price","countermove","delayed"]){
   if(typeof p[k]!=="string"||p[k].trim().length<20)errors.push("missing "+k+" "+p.id);
  }
 }
 return {valid:errors.length===0,count:items.length,domains:[...new Set(items.map(x=>x.domain))],errors};
}
/**
 * Director-only palette. Mechanism IDs must be connected to OBSERVED signals before
 * modeling any causal response. Never reveal this overlay as player truth.
 */
export function mechanismCandidates({domain,signal}={}){
 return STRATEGIC_MECHANISMS.filter(p=>(!domain||p.domain===domain)&&
   (!signal||p.signal.includes(signal)||p.name.includes(signal)));
}
